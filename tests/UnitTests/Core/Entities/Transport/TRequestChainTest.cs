using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using Transport.Core.Entities.Transport;
using Transport.Core.Entities.User;
using Transport.Core.Enums;

namespace UnitTests.Core.Entities.Transport
{
	[TestClass]
	public class TRequestChainTest
	{
		[TestMethod]
		public void PC_ConfirmsNTest()
		{
			var chain = new TransportRequestConfirmChain();
			Assert.IsNull(chain.Confirms);
		}

		[TestMethod]
		public void PC_StateFTest()
		{
			var chain = new TransportRequestConfirmChain();
			//Empty Chain Must Be Not Rejected, Nor Confirmed But Initial
			Assert.IsTrue(!chain.IsRejected && !chain.IsConfirmed && chain.IsInitial
				&& chain.ConfirmState == RequestState.Initial);
		}

		[TestMethod]
		public void PC_ChainStateNTest()
		{
			var chain = new TransportRequestConfirmChain();
			//Empty Chain Confirm Chain State Should Be Null
			Assert.IsNull(chain.ConfirmChainState);
		}

		public TransportRequestConfirmChain GenerateChain(out TransportRequest request)
		{
			request = new TransportRequest();
			var userLevels = new List<Tuple<AppUser, int>>()
			{
				new Tuple<AppUser, int>(new AppUser(){ Id = "1" }, 1),
				new Tuple<AppUser, int>(new AppUser(){ Id = "2" }, 2),
			};
			return new TransportRequestConfirmChain(request, userLevels);
		}

		[TestMethod]
		public void FC_StateFTest()
		{
			var chain = GenerateChain(out _);
			//Not Empty Chain Must Be Not Rejected, Nor Confirmed But Initial
			Assert.IsTrue(!chain.IsRejected && !chain.IsConfirmed && chain.IsInitial
				&& chain.ConfirmState == RequestState.Initial);
		}

		[TestMethod]
		public void FC_ChainStateTest()
		{
			var chain = GenerateChain(out _);
			//Not Empty Chain Confirm Chain State Must Not Be Null
			//But Equals To First Highest Priority Confirm Object
			var realCCState = chain.Confirms?.OrderByDescending(c => c.Priority).FirstOrDefault(c => c.IsInitial);

			Assert.AreEqual(chain.ConfirmChainState, realCCState);
		}

		[TestMethod]
		public void FC_ConfirmsInitTest()
		{
			var chain = GenerateChain(out TransportRequest request);

			//All Data Generated By Chain Generator Must Be Present In Chain Confirms
			var i1Exists = chain.Confirms.Any(c => c.Request == request && c.User.Id == "1" && c.Priority == 1);
			var i2Exists = chain.Confirms.Any(c => c.Request == request && c.User.Id == "2" && c.Priority == 2);

			Assert.IsTrue(i1Exists && i2Exists);
		}

		public void StateChanger(TransportRequestConfirmChain chain, RequestState state)
		{
			foreach (var confirm in chain.Confirms) confirm.State = state;
		}

		[TestMethod]
		public void FC_IsConfirmedTest()
		{
			var chain = GenerateChain(out _);
			StateChanger(chain, RequestState.Confirmed);
			//Chain With All Confirms Confirmed Must Be Confirmed!
			Assert.IsTrue(chain.IsConfirmed);
		}

		[TestMethod]
		public void FC_IsRejectedTest()
		{
			var chain = GenerateChain(out _);
			StateChanger(chain, RequestState.Rejected);
			//Chain With All Confirms Confirmed Must Be Confirmed!
			Assert.IsTrue(chain.IsRejected);
		}

		[TestMethod]
		public void FC_IsInitialTest()
		{
			var chain = GenerateChain(out _);
			StateChanger(chain, RequestState.Confirmed);
			chain.Confirms.Last().State = RequestState.Initial;
			//Chain With At Least One Initial Confirm Must Be Initial!
			Assert.IsTrue(chain.IsInitial);
		}
	}
}
